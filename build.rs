use std::{collections::BTreeMap, env, fs, path::PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    let mut endpoints_by_domain = BTreeMap::<String, Vec<_>>::new();
    for (path, method_name, empty_response) in ENDPOINTS {
        let mut segments = path
            .strip_prefix('/')
            .expect("endpoint path starts with slash")
            .split('/');
        let domain = segments.next().expect("endpoint has a domain").to_owned();
        let module_path = segments
            .map(|segment| segment.replace('-', "_"))
            .collect::<Vec<_>>()
            .join("::");
        endpoints_by_domain
            .entry(domain)
            .or_default()
            .push((*path, *method_name, *empty_response, module_path));
    }

    let manifest_dir = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("manifest dir is set"));
    for (domain, endpoints) in endpoints_by_domain {
        let mut generated = format!(
            "// AUTO-GENERATED by build.rs. Do not edit this file manually.\nuse crate::mi_api_types::{domain};\n\nimpl super::super::Client {{\n"
        );
        for (path, method_name, empty_response, module_path) in endpoints {
            let type_path = if module_path.is_empty() {
                domain.clone()
            } else {
                format!("{domain}::{module_path}")
            };
            let helper = if empty_response { "http_api_empty" } else { "http_api" };
            generated.push_str(&format!(
                "    pub async fn {method_name}(\n        &self,\n        request: {type_path}::Request,\n    ) -> anyhow::Result<{type_path}::Response> {{\n        self.{helper}(\"{path}\", &request).await\n    }}\n\n"
            ));
        }
        generated.push_str("}\n");

        let output_dir = manifest_dir.join("src/client/generated");
        fs::create_dir_all(&output_dir).expect("create generated Client module directory");
        let output = output_dir.join(format!("{domain}.rs"));
        let current = fs::read_to_string(&output).unwrap_or_default();
        if current != generated {
            fs::write(output, generated).expect("write generated Client methods");
        }
    }
}

